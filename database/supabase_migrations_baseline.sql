-- Jalankan hanya jika tabel aplikasi sudah dibuat manual/oleh SQL lain
-- dan migration table Laravel belum berisi migration Supabase.

CREATE TABLE IF NOT EXISTS migrations (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    migration varchar(255) NOT NULL,
    batch integer NOT NULL
);

-- Tandai migration yang skema tabelnya sudah ada manual.
-- Jangan jalankan migrate:fresh atau migrate:reset.
INSERT INTO migrations (migration, batch)
SELECT migration_name, 1
FROM (VALUES
    ('0001_01_01_000000_create_users_table'),
    ('0001_01_01_000001_create_cache_table'),
    ('0001_01_01_000002_create_jobs_table'),
    ('2026_01_01_000001_create_master_tables'),
    ('2026_01_01_000002_create_batch_tables'),
    ('2026_01_01_000003_create_operational_tables'),
    ('2026_01_01_000004_create_health_and_inventory_tables'),
    ('2026_01_01_000005_create_finance_and_system_tables'),
    ('2026_11_23_000001_create_personal_access_tokens_table')
) AS baseline(migration_name)
WHERE NOT EXISTS (
    SELECT 1 FROM migrations m WHERE m.migration = baseline.migration_name
);

-- Setelah baseline, migration repair dapat dicatat oleh Laravel.
SELECT migration, batch
FROM migrations
ORDER BY id;
